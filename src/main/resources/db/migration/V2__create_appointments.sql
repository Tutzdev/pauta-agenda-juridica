CREATE TABLE appointments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(160) NOT NULL,
    type              VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    scheduled_date    DATE         NOT NULL,
    start_time        TIME,
    duration_minutes  INTEGER,
    location          VARCHAR(160),
    process_number    VARCHAR(25),
    client_id         BIGINT REFERENCES clients (id),
    notes             VARCHAR(4000),
    completed_at      TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_appointments_duration CHECK (duration_minutes IS NULL OR duration_minutes BETWEEN 5 AND 720),
    CONSTRAINT ck_appointments_time_duration CHECK ((start_time IS NULL) = (duration_minutes IS NULL))
);

CREATE INDEX idx_appointments_date ON appointments (scheduled_date, start_time);
CREATE INDEX idx_appointments_client ON appointments (client_id);
CREATE INDEX idx_appointments_open_type ON appointments (status, type, scheduled_date);
